  rows.map((r, i) => ({
    id: r[0],
    no: offset + i + 1,
    nameKo: r[1],
    scientificName: r[2],
    group,
    taxon: r[3],
    tier: r[4],
    icon: r[5],
    feature: r[6],
    habitat: r[7],
    season: r[8],
    role: r[9],
    similar: r[10],
  }));

